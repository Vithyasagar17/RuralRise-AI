"""Opt-in real PostgreSQL tests. Use a dedicated disposable database only.

Set RURALRISE_TEST_DATABASE_URL and RURALRISE_ALLOW_DATABASE_TESTS=1.
The migration creates only ruralrise_backend; tests never drop schemas/tables.
"""
import concurrent.futures
import os
import unittest
from uuid import uuid4
from datetime import datetime, timezone

from fastapi.testclient import TestClient
from app.config import BACKEND_DIR, Settings
from app.database import MissingStudent, StorageUnavailable, demo_profiles
from app.main import create_app
from inprocess_loop import InProcessEventLoop

TEST_URL = os.getenv("RURALRISE_TEST_DATABASE_URL", "")
ENABLED = bool(TEST_URL) and os.getenv("RURALRISE_ALLOW_DATABASE_TESTS") == "1"
PROFILE = demo_profiles()[0]["profile"]
CLIENT_OPTIONS = {"backend_options": {"loop_factory": InProcessEventLoop}}


@unittest.skipUnless(ENABLED, "Real database tests require an explicitly configured dedicated test database")
class PostgresIntegrationTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        from app.postgres_store import PostgresStore
        cls.config = Settings(BACKEND_DIR / "data", BACKEND_DIR / "var/unused-test.json", (),
                              storage_backend="postgres", database_url=TEST_URL,
                              db_sslmode=os.getenv("RURALRISE_TEST_DB_SSLMODE", "require"))
        cls.store = PostgresStore(cls.config)
        cls.store.migrate()
        cls.store.seed_demo()

    def setUp(self):
        self.ids = []

    def tearDown(self):
        # Only IDs generated by this individual test are deleted; no broad cleanup.
        if self.ids:
            with self.store.transaction() as cursor:
                cursor.execute("DELETE FROM ruralrise_backend.learning_progress WHERE student_id = ANY(%s)", (self.ids,))
                cursor.execute("DELETE FROM ruralrise_backend.student_profiles WHERE student_id = ANY(%s)", (self.ids,))

    def create_profile(self, profile=None):
        result = self.store.create_profile(profile or PROFILE)
        self.ids.append(result["student_id"])
        return result

    def test_migration_rerun_and_schema_check(self):
        version = self.store.check()["migration_version"]
        self.assertEqual(self.store.migrate(), {"migration_version": version, "applied": False})
        self.assertEqual(self.store.check()["backend"], "postgres")

    def test_profile_roundtrip_with_unicode_and_sql_punctuation(self):
        profile = {**PROFILE, "name": "மாணவி O'Neil; SELECT 1;"}
        created = self.create_profile(profile)
        self.assertEqual(self.store.get_profile(created["student_id"])["profile"], profile)
        self.assertIn(self.store.check()["migration_version"], (1, 2))

    def test_progress_upsert_and_recreated_connection_store(self):
        from app.postgres_store import PostgresStore
        student_id = self.create_profile()["student_id"]
        update = {"student_id": student_id, "course_id": "demo-safety", "completed": True, "score": 80}
        self.store.save_progress(update)
        self.store.save_progress({**update, "score": 90})
        fresh = PostgresStore(self.config)
        self.assertEqual(len(fresh.get_progress(student_id)), 1)
        self.assertEqual(fresh.get_progress(student_id)[0]["score"], 90)

    def test_http_contract_with_real_database(self):
        with TestClient(create_app(self.config), **CLIENT_OPTIONS) as client:
            response = client.post("/profile", json=PROFILE)
            self.assertEqual(response.status_code, 201)
            student_id = response.json()["student_id"]
            self.ids.append(student_id)
            update = {"student_id": student_id, "course_id": "demo-safety", "completed": True, "score": 80}
            response = client.post("/progress", json=update)
            self.assertEqual(response.status_code, 200)
            self.assertEqual(set(response.json()), {"saved", "progress"})
            self.assertEqual(response.json()["progress"]["score"], 80)
            result = client.get("/facilitator/students").json()
            self.assertNotIn(student_id, [x["student_id"] for x in result["students"]])

    def test_unknown_student_and_course(self):
        missing = str(uuid4())
        with self.assertRaises(MissingStudent):
            self.store.get_profile(missing)
        with TestClient(create_app(self.config), **CLIENT_OPTIONS) as client:
            self.assertEqual(client.post("/progress", json={"student_id": missing,
                "course_id": "demo-safety", "completed": True}).status_code, 404)
            student_id = self.create_profile()["student_id"]
            self.assertEqual(client.post("/progress", json={"student_id": student_id,
                "course_id": "nonexistent", "completed": True}).status_code, 404)

    def test_database_score_constraint_and_rollback(self):
        student_id = self.create_profile()["student_id"]
        with self.assertRaises(StorageUnavailable):
            with self.store.transaction() as cursor:
                cursor.execute("""INSERT INTO ruralrise_backend.learning_progress
                    (student_id, course_id, completed, score) VALUES (%s, %s, %s, %s)""",
                    (student_id, "demo-safety", True, -1))
        self.assertEqual(self.store.get_progress(student_id), [])

    def test_concurrent_progress_writes_have_one_row(self):
        student_id = self.create_profile()["student_id"]
        def update(score):
            return self.store.save_progress({"student_id": student_id, "course_id": "demo-safety", "completed": True, "score": score})
        with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
            records = list(pool.map(update, range(12)))
        self.assertEqual(len(records), 12)
        self.assertEqual(len(self.store.get_progress(student_id)), 1)

    def test_import_keeps_ids_and_is_repeatable_without_overwrite(self):
        student_id = str(uuid4())
        self.ids.append(student_id)
        stamp = datetime(2026, 10, 18, 9, 32, 59, tzinfo=timezone.utc).isoformat()
        state = {"profiles": [{"student_id": student_id, "profile": PROFILE, "created_at": stamp}],
                 "progress": [{"student_id": student_id, "course_id": "demo-safety", "completed": True,
                               "score": 80, "updated_at": stamp}]}
        first = self.store.import_snapshot(state)
        self.assertEqual((first["profiles_inserted"], first["progress_inserted"]), (1, 1))
        self.assertEqual(self.store.get_progress(student_id)[0]["updated_at"], stamp)
        self.store.save_progress({"student_id": student_id, "course_id": "demo-safety", "completed": True, "score": 90})
        second = self.store.import_snapshot(state)
        self.assertEqual((second["profiles_inserted"], second["progress_inserted"]), (0, 0))
        self.assertEqual(self.store.get_progress(student_id)[0]["score"], 90)

    def test_import_fk_failure_rolls_back_earlier_profile_insert(self):
        student_id = str(uuid4())
        self.ids.append(student_id)
        stamp = datetime.now(timezone.utc).isoformat()
        # Intentionally bypass loader validation to force a real SQL foreign-key failure.
        state = {"profiles": [{"student_id": student_id, "profile": PROFILE, "created_at": stamp}],
                 "progress": [{"student_id": str(uuid4()), "course_id": "demo-safety", "completed": True,
                               "score": 80, "updated_at": stamp}]}
        with self.assertRaises(StorageUnavailable):
            self.store.import_snapshot(state)
        with self.assertRaises(MissingStudent):
            self.store.get_profile(student_id)

    def test_rows_are_not_public_and_rls_is_enabled(self):
        with self.store.transaction() as cursor:
            cursor.execute("""SELECT c.relname, c.relrowsecurity FROM pg_class c
                JOIN pg_namespace n ON n.oid = c.relnamespace
                WHERE n.nspname = 'ruralrise_backend' AND c.relkind = 'r'""")
            rows = cursor.fetchall()
            self.assertTrue({"schema_migrations", "student_profiles", "learning_progress"}.issubset(
                {row["relname"] for row in rows}))
            self.assertTrue(all(row["relrowsecurity"] for row in rows))
            cursor.execute("""SELECT count(*) AS policies FROM pg_policies WHERE schemaname = 'ruralrise_backend'""")
            self.assertEqual(cursor.fetchone()["policies"], 0)


if __name__ == "__main__":
    unittest.main()
